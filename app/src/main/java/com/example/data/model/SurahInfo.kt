  fun getSurahByNumber(number: Int): SurahInfo? = surahs.find { it.number == number }

  fun getGlobalAyahId(surahNumber: Int, ayahNumberInSurah: Int): Int {
    val surah = getSurahByNumber(surahNumber) ?: surahs.first()
    val clampedAyah = ayahNumberInSurah.coerceIn(1, surah.numberOfAyahs)
    return surah.startAyahGlobalId + (clampedAyah - 1)
  }

  fun getSurahAndAyahFromGlobalId(globalId: Int): Pair<SurahInfo, Int> {
    val surah = surahs.lastOrNull { it.startAyahGlobalId <= globalId } ?: surahs.first()
    val ayahInSurah = (globalId - surah.startAyahGlobalId + 1).coerceIn(1, surah.numberOfAyahs)
    return Pair(surah, ayahInSurah)
  }
